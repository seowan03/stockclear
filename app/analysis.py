import pandas as pd


def analyze_inventory(df: pd.DataFrame) -> pd.DataFrame:
    """
    Excel에서 가져온 재고 데이터를 분석한다.

    필수 컬럼:
    상품명, 재고량, 원가, 입고일, 판매가, 판매량

    계산 컬럼:
    보관기간, 재고금액, 판매속도, 예상소진기간, 감가율
    """

    # --------------------------------
    # 1. 입고일을 날짜 형식으로 변환
    # --------------------------------
    df["입고일"] = pd.to_datetime(
        df["입고일"],
        errors="coerce"
    )

    # 날짜 변환에 실패한 데이터 확인
    if df["입고일"].isnull().any():
        raise ValueError(
            "입고일 데이터에 잘못된 날짜가 있습니다."
        )

    # --------------------------------
    # 2. 현재 날짜
    # --------------------------------
    today = pd.Timestamp.today().normalize()

    # --------------------------------
    # 3. 보관기간 계산
    # --------------------------------
    # 현재 날짜 - 입고일
    df["보관기간"] = (
        today - df["입고일"]
    ).dt.days

    # --------------------------------
    # 4. 재고금액 계산
    # --------------------------------
    # 재고량 × 원가
    df["재고금액"] = (
        df["재고량"] * df["원가"]
    )

    # --------------------------------
    # 5. 판매속도 계산
    # --------------------------------
    # 판매량 ÷ 보관기간
    df["판매속도"] = df.apply(
        lambda row:
            row["판매량"] / row["보관기간"]
            if row["보관기간"] > 0
            else 0,
        axis=1
    )

    # --------------------------------
    # 6. 예상 소진 기간 계산
    # --------------------------------
    # 현재 재고량 ÷ 하루 평균 판매량
    df["예상소진기간"] = df.apply(
        lambda row:
            row["재고량"] / row["판매속도"]
            if row["판매속도"] > 0
            else 9999,
        axis=1
    )

    # --------------------------------
    # 7. 감가율 계산
    # --------------------------------
    # (원가 - 판매가) ÷ 원가 × 100
    df["감가율"] = df.apply(
        lambda row:
            ((row["원가"] - row["판매가"]) / row["원가"]) * 100
            if row["원가"] > 0
            else 0,
        axis=1
    )

    # --------------------------------
    # 8. API에서 사용할 수 있도록
    #    컬럼명을 영어로 변환
    # --------------------------------
    df = df.rename(columns={
        "상품명": "product_name",
        "재고량": "stock_qty",
        "원가": "purchase_price",
        "입고일": "received_date",
        "판매가": "selling_price",
        "판매량": "sales_qty",

        "보관기간": "storage_days",
        "재고금액": "inventory_value",
        "판매속도": "sales_speed",
        "예상소진기간": "days_to_sell",
        "감가율": "depreciation_rate"
    })

    return df